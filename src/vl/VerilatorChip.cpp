constexpr int kAbi = 1;
constexpr const char* kModule = "tt_um_chiply";

std::string quote(const std::string& s)
{
    std::string r = "'";
    for (char c : s)
        r += (c == '\'') ? std::string("'\\''") : std::string(1, c);
    return r + "'";
}

// Runs a shell command; returns its exit status and output (stdout+stderr).
int run(const std::string& cmd, std::string* out)
{
    std::string text;
    FILE* f = popen((cmd + " 2>&1").c_str(), "r");
    if (!f) {
        if (out)
            *out = "cannot run: " + cmd;
        return -1;
    }
    char buf[4096];
    while (std::size_t n = fread(buf, 1, sizeof buf, f))
        text.append(buf, n);
    const int st = pclose(f);
    if (out)
        *out = text;
    return WIFEXITED(st) ? WEXITSTATUS(st) : -1;
}

std::string trim(std::string s)
{
    while (!s.empty() && (s.back() == '\n' || s.back() == '\r' || s.back() == ' '))
        s.pop_back();
    return s;
}

std::string findExecutable(const char* name, const std::vector<std::string>& extra)
{
    std::vector<std::string> dirs;
    if (const char* path = std::getenv("PATH")) {
        std::stringstream ss(path);
        for (std::string d; std::getline(ss, d, ':');)
            if (!d.empty())
                dirs.push_back(d);
    }
    dirs.insert(dirs.end(), extra.begin(), extra.end());
    for (const std::string& d : dirs) {
        const fs::path p = fs::path(d) / name;
        std::error_code ec;
        if (fs::is_regular_file(p, ec) && access(p.c_str(), X_OK) == 0)
            return p.string();
    }
    return {};
}

std::uint64_t fnv(const std::string& s, std::uint64_t h = 1469598103934665603ULL)
{
    for (unsigned char c : s) {
        h ^= c;
        h *= 1099511628211ULL;
    }
    return h;
}

std::string hex(std::uint64_t v)
{
    char b[17];
    std::snprintf(b, sizeof b, "%016llx", static_cast<unsigned long long>(v));
    return b;
}

void writeFile(const fs::path& p, const std::string& text)
{
    std::ofstream f(p, std::ios::binary);
    f << text;
    if (!f)
        throw BuildError("cannot write " + p.string());
}

