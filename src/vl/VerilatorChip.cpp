std::vector<std::string> archFlags()
{
#if defined(__APPLE__) && defined(__aarch64__)
    return {"-arch", "arm64"};
#elif defined(__APPLE__) && defined(__x86_64__)
    return {"-arch", "x86_64"};
#else
    return {};
#endif
}

std::string joinArgs(const std::vector<std::string>& a)
{
    std::string s;
    for (const std::string& x : a)
        s += " " + quote(x);
    return s;
}

// The generated C entry points Chiply loads.
std::string wrapperSource(const VerilogNetMap& map)
{
    std::ostringstream o;
    o << "// Generated by Chiply. Do not edit.\n"
         "#include \"Vchip.h\"\n#include \"Vchip___024root.h\"\n#include \"verilated.h\"\n#include <cstdint>\n"
         "double sc_time_stamp() { return 0; }\n"
         "namespace { struct Model { VerilatedContext ctx; Vchip* top = nullptr; }; }\n"
         "extern \"C\" {\n"
         "int chiply_vl_abi() { return " << kAbi << "; }\n"
         "int chiply_vl_count() { return " << map.number.size() << "; }\n"
         "void* chiply_vl_new(int mode, unsigned long long seed) {\n"
         "  auto* m = new Model;\n"
         "  m->ctx.randReset(mode);\n"
         "  m->ctx.randSeed(int(seed & 0x7fffffffULL));\n"
         "  m->top = new Vchip(&m->ctx);\n"
         "  m->top->ena = 1;\n"
         "  return m;\n}\n"
         "void chiply_vl_free(void* p) { auto* m = static_cast<Model*>(p); delete m->top; delete m; }\n"
         "void chiply_vl_eval(void* p, unsigned char ui, unsigned char uio, unsigned char clk, unsigned char rst) {\n"
         "  Vchip* t = static_cast<Model*>(p)->top;\n"
         "  t->ui_in = ui; t->uio_in = uio; t->clk = clk; t->rst_n = rst; t->ena = 1;\n"
         "  t->eval();\n}\n"
         "void chiply_vl_read(void* p, unsigned char* o) {\n"
         "  const auto* r = static_cast<Model*>(p)->top->rootp;\n";
    for (std::size_t i = 0; i < map.number.size(); ++i)
        o << "  o[" << i << "] = r->" << kModule << "__DOT__net" << map.number[i] << " & 1;\n";
    o << "}\n}\n";
    return o.str();
}

class VerilatorBackend : public sim::ChipBackend {
public:
    VerilatorBackend(void* lib, std::vector<int> nets, std::string name)
        : m_nets(std::move(nets))
        , m_name(std::move(name))
    {
        m_new = reinterpret_cast<void* (*)(int, unsigned long long)>(dlsym(lib, "chiply_vl_new"));
        m_free = reinterpret_cast<void (*)(void*)>(dlsym(lib, "chiply_vl_free"));
        m_eval = reinterpret_cast<void (*)(void*, unsigned char, unsigned char, unsigned char, unsigned char)>(
            dlsym(lib, "chiply_vl_eval"));
        m_read = reinterpret_cast<void (*)(void*, unsigned char*)>(dlsym(lib, "chiply_vl_read"));
        if (!m_new || !m_free || !m_eval || !m_read)
            throw BuildError("the chip library is missing entry points");
    }
    ~VerilatorBackend() override
    {
        if (m_model)
            m_free(m_model);
        // The library stays loaded: dlclose of a Verilated model's library
        // is not safe while its statics may still be referenced.
    }
    std::string name() const override { return m_name; }
    const std::vector<int>& nets() const override { return m_nets; }
    void reset(sim::FlopStart start, std::uint64_t seed) override
    {
        if (m_model)
            m_free(m_model);
        if (seed == 0)
            seed = std::random_device{}();
        m_model = m_new(start == sim::FlopStart::Zero ? 0 : 2, seed);
    }
    void eval(std::uint8_t ui, std::uint8_t uio, bool clk, bool rstN) override
    {
        if (!m_model)
            reset(sim::FlopStart::Random, 0);
        m_eval(m_model, ui, uio, clk, rstN);
    }
    void read(std::vector<std::uint8_t>& v) override
    {
        v.resize(m_nets.size());
        if (m_model && !v.empty())
            m_read(m_model, v.data());
    }

private:
    std::vector<int> m_nets;
    std::string m_name;
    void* m_model = nullptr;
    void* (*m_new)(int, unsigned long long) = nullptr;
    void (*m_free)(void*) = nullptr;
    void (*m_eval)(void*, unsigned char, unsigned char, unsigned char, unsigned char) = nullptr;
    void (*m_read)(void*, unsigned char*) = nullptr;
};

